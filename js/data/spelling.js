/* Ortografia: luka w prawdziwym słowie.
   band 1 ó/u, band 2 rz/ż, band 3 ch/h, band 4 ą/om oraz ę/en.
   missing musi występować w słowie dokładnie raz. */

function g(id, word, missing, options, meaning, band, hint) {
  const at = word.indexOf(missing);
  if (at < 0 || word.indexOf(missing, at + 1) !== -1) {
    throw new Error(`Luka „${missing}” w „${word}”`);
  }
  return {
    id,
    word,
    before: word.slice(0, at),
    after: word.slice(at + missing.length),
    missing,
    options,
    meaning,
    band,
    hint,
  };
}

