export function voiById(id) {
  return VOIVODESHIPS.find((item) => item.id === id) || null;
}

export function neighborsOf(id) {
  return (NEIGHBORS[id] || []).map(voiById).filter(Boolean);
}

export function zoneOf(city) {
  const voi = voiById(city.voi);
  const dy = city.lat - voi.lat;
  const dx = city.lon - voi.lon;
  if (Math.abs(dy) < 0.28 && Math.abs(dx) < 0.38) return "środek";
  if (Math.abs(dy) >= Math.abs(dx) * 0.85) return dy > 0 ? "północ" : "południe";
  return dx > 0 ? "wschód" : "zachód";
}

